"""First-degree LinkedIn connections at target companies, from the user's own Connections.csv export.

LinkedIn > Settings > Data privacy > Get a copy of your data > Connections gives a CSV; drop it at
data/careerops/Connections.csv (gitignored: third-party PII). career-ops's linkedin-join.mjs then
joins it offline against the companies on today's cards. Names are rendered into the report only
and never stored in a snapshot.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from .careerops import CareerOpsError, data_root, run_json, unavailable_reason
from .models import Job

JOIN = "linkedin-join.mjs"
MAX_SHOWN = 4


def csv_path(root: Path) -> Path:
    return data_root(root) / "Connections.csv"


def has_export(root: Path) -> bool:
    return csv_path(root).exists()


def write_portals(root: Path, names: list[str]) -> Path:
    """portals.yml with one tracked_companies entry per name; the only input the join needs besides the CSV."""
    p = data_root(root) / "portals.yml"
    doc = {"tracked_companies": [{"name": n} for n in sorted(set(names)) if n.strip()]}
    p.write_text("# generated by job-radar for linkedin-join.mjs; edit config/companies.yaml instead\n"
                 + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True))
    return p


def _conn(c: dict[str, Any]) -> dict[str, str]:
    return {"name": str(c.get("name") or ""), "title": str(c.get("title") or ""), "linkedin": str(c.get("linkedin") or ""),
            "match": str(c.get("match") or ""), "connected_on": str(c.get("connectedOn") or "")[:10],
            "linkedin_company": str(c.get("linkedinCompany") or "")}


def parse_join(out: dict[str, Any], names: list[str]) -> dict[str, list[dict[str, str]]]:
    """Map each requested company name to its connections (exact and strong matches first, as the join orders them)."""
    by_fold = {n.casefold(): n for n in names}
    result: dict[str, list[dict[str, str]]] = {}
    for t in out.get("targets") or []:
        company = str(t.get("company") or "")
        key = by_fold.get(company.casefold(), company)
        conns = [_conn(c) for c in t.get("connections") or [] if c.get("name")]
        if conns:
            result.setdefault(key, []).extend(conns)
    return result


def join(root: Path, names: list[str], *, include_weak: bool = False) -> dict[str, list[dict[str, str]]]:
    write_portals(root, names)
    args = ["--portals-only", "--csv", str(csv_path(root).resolve())] + (["--include-weak"] if include_weak else [])
    env = {"CAREER_OPS_ROOT": str(data_root(root).resolve())}          # where portals.yml was just written
    return parse_join(run_json(root, JOIN, args, env=env, timeout=120), names)


def store_path(root: Path) -> Path:
    return data_root(root) / "connections.json"


def load_store(root: Path) -> dict[str, list[dict[str, str]]]:
    p = store_path(root)
    return json.loads(p.read_text()) if p.exists() else {}


def annotate(jobs: list[Job], root: Path, *, warnings: list[str] | None = None,
             join_fn=None) -> dict[str, list[dict[str, str]]]:
    """Connections per company for today's jobs; {} when no export is present (the feature is opt-in)."""
    warnings = warnings if warnings is not None else []
    if not has_export(root):
        return {}
    reason = unavailable_reason(root)
    if reason:
        warnings.append(f"connections: {reason}")
        return load_store(root)
    names = sorted({j.company for j in jobs})
    try:
        found = (join_fn or (lambda ns: join(root, ns)))(names)
    except CareerOpsError as e:
        warnings.append(f"connections: {e}")
        return load_store(root)
    store_path(root).write_text(json.dumps(found, indent=1, ensure_ascii=False) + "\n")
    return found
